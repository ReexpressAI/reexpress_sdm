##################### Overview
#########################################################################################################

# This short demo examines a small example of the task of binary classification of instruction-following where we seek to classify whether or not the generated response from a model correctly and faithfully answers the user's instructions, where the ground truth labels correspond to y = 0 = "Not Verified" and y = 1 = "Verified". This uses a small sample of data from OpenVerification1. In this sample, the model summary and explanation are generated by gpt-5.5-2026-04-23. The file eval_ood.jsonl is a synthetically generated far out-of-distribution dataset constructed by randomly shuffling the characters of the model summary and explanation. In this case, for illustrative purposes, the embeddings of the agreement model are from the publicly available mlx-community/gemma-4-31b-it-4bit model, and are constructed from the final-layer hidden states, concatenating the following:
#
# max-pool over the sequence :: mean-pool over the sequence :: hidden-state of the final token (that estimates Yes | No)
#
# As such, the embeddings contain 3 x 5376 = 16128 dimensions.
#
# To streamline the data files, the "document" field in the JSON only includes the agreement prompt given to the mlx-community/gemma-4-31b-it-4bit model in generating the embeddings. The "attributes" field is omitted, and as such, the binary classification from gpt-5.5-2026-04-23 is not included.
#
# Instructions on reproducing this dataset from the source data is available in https://github.com/ReexpressAI/reexpress_mcp_server/blob/main/code/data_processing/code/mlx_examples/small_illustrative_demo_for_using_gemma4_with_v2.5.1_data.sh.
#
# This is a small, simplified dataset constructed for this tutorial. For more substantive examples, as well as additional context on this notion of instruction-following, see the Reexpress MCP Server repo. This task has been previously considered in the following work:

# > Allen Schmaltz. 2026. Introspectable, Updatable, and Uncertainty-aware Classification of Language Model Instruction-following. In Proceedings of the ACM Conference on AI and Agentic Systems (CAIS '26). Association for Computing Machinery, New York, NY, USA, 1259--1269. https://doi.org/10.1145/3786335.3813214.

