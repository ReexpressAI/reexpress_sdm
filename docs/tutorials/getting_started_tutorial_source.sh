# `sdm train` learns the parameters of the SDM activation (the final-layer adaptor) AND runs the calibration algorithm to partition the calibration set. Once `sdm train` completes, the model is ready to be used to predict over new, unseen data.

# Here, we train for 2 iterations of 500 epochs each. For the purposes of the tutorial, feel free to reduce the number of iterations or epochs for faster training. As a back-of-the-envelope guide, each epoch on an M2 Ultra 76 core Mac Studio takes about 0.66 seconds, and around 11 minutes for the full run. For a production setting, we would train with additional iterations and epochs (and ideally, a larger dataset). Interestingly, an advantageous property of the SDM estimator is that such calibration is relatively robust to under-trained, or otherwise poorly optimized, models. (The estimator will tend to be conservative in those cases. Training the adaptor using the standard cross-entropy loss, which is equivalent to the SDM loss with the instance-wise regularization terms set at a constant q=e-2 and d=1, will also tend to not "break" calibration, but the estimator will tend to be more conservative than when training with the SDM loss.) Such variations are easy to examine here and with the macOS app Reexpress two. Your exact results below may differ from ours depending on the options you choose.

# as with other commands, use `sdm train --help` to see the available arguments (and defaults)

# Note that --composition determines what fields in the JSON lines files will be used as input to the SDM activation. For convenience, we separate "embedding" and "attributes" if, for bookkeeping, you want to separate the core embeddings from other features, but you are free to choose the semantics of those fields, or to altogether ignore that distinction and only use the "embedding" field, or only the "attributes" field. If you choose "embedding+attributes", both vectors are concatenated together as input to the SDM activation. The important point is to be consistent for a given model and subsequent evaluation/deployment.

# FYI: If specified at training, the same values for --representation_fingerprint and --class_names must be used at test time, including when importing into Reexpress two.

