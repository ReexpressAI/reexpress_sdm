echo "${MODEL_DIR}/logs.txt"  # training output is redirected to logs.txt; use `tail -f "${MODEL_DIR}/logs.txt"` to watch progress
#/Users/a/Documents/project_tutorials/models/instruction_following.gemma_4_31b_it_4bit/logs.txt

# `sdm train` auto-selects the device (CUDA, then MPS, then CPU); add `--device=cpu|mps|cuda` to choose explicitly.

sdm train \
--training="${TRAIN_FILE}" \
--calibration="${CALIBRATION_FILE}" \
--number_of_classes 2 \
--representation_fingerprint embedding_v1 \
--output "${MODEL_FILE}" \
--alpha_resolution=${ALPHA_RESOLUTION} \
--epochs 500 \
--number_of_random_shuffles=2 \
--batch_size 64 \
--learning_rate ${LEARNING_RATE} \
--max_neighbors 2048 \
--exemplar_dimension ${EXEMPLAR_DIMENSION} \
--composition="embedding" \
--report_output="${MODEL_DIR}/report.txt" > "${MODEL_DIR}/logs.txt" 2>&1

echo "${MODEL_DIR}/report.txt"  # summary report of training
#/Users/a/Documents/project_tutorials/models/instruction_following.gemma_4_31b_it_4bit/report.txt
  
# checks the model file is well-formed:
sdm artifact validate --model "${MODEL_FILE}"
# provides summary stats, including the q'_min values and thresholds for each calibration region for which the class- and prediction-conditional accuracy is estimated to be at least a given alpha:
sdm artifact inspect --model "${MODEL_FILE}"
# In this case, the most conservative region into which the calibration set was able to be partitioned was alpha=0.99, followed by alpha 0.98 and 20 additional descending regions down to 0.51.

