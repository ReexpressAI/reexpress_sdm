python - \
  "${MODEL_FILE}" \
  "${EVAL_OUTPUT_DIR}/best_training_scored.sdmdataset" \
  "${EVAL_OUTPUT_DIR}/best_training_scored.overall_evaluation_report.json" <<'PY'
import json
import sys
from pathlib import Path
from reexpress_sdm import Dataset, SDMController

model_path, input_path, output_path = sys.argv[1:]
controller = SDMController.load(model_path)
dataset = Dataset.load(
    input_path,
    expected_dimension=controller.model.embedding_dimension,
    number_of_classes=controller.model.number_of_classes,
    require_labels=True,
)
dataset.validate_class_names(controller.model.configuration["classNames"])

# Require the explicit exclusions saved by selected-training export.
identities = [row["excludedSupportIndex"] for row in dataset.rows]
if any(index is None for index in identities):
    raise ValueError("Every selected-training row must have a support exclusion")

scores = controller.score(
    dataset.vectors,
    ids=dataset.ids,
    representation_fingerprint=dataset.representation_fingerprint,
    identity_support_indices=identities,
)
report = {
    "evaluation": controller.evaluate(scores, dataset.labels),
    "distribution": controller.summarize_distribution(scores),
}
Path(output_path).write_text(
    json.dumps(report, indent=2, allow_nan=False) + "\n", encoding="utf-8"
)
PY

# This recomputes scores with self-exclusions and writes the same evaluation and distribution report structure as the CLI. Missing exclusions cause an error.

